"""Builds the recorded fallback voice: shared/audio-en.js and shared/audio-de.js (needs espeak-ng and ffmpeg).
   node tools/collect_speech.mjs > /tmp/speech.json && python3 tools/make_clips.py
   These clips are only used when a phone's own voice does not work. They sound simple and robotic."""
import base64, json, os, subprocess, tempfile
from concurrent.futures import ThreadPoolExecutor
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open('/tmp/speech.json'))
EN_L = dict(zip('ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'ay bee see dee ee eff gee aitch eye jay kay ell em en oh pee cue ar ess tee you vee,double you,ex,why,zed'.replace(',', ' ').replace('double you', 'double-you').split()))
EN_L['W'] = 'double you'
DE_L = dict(zip('ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'ah beh zeh deh eh eff geh hah ih jott kah ell emm enn oh peh kuh err ess teh uh fau weh iks üpsilon zett'.split()))
UML = {'Ä': 'äh', 'Ö': 'öh', 'Ü': 'üh', 'ä': 'äh', 'ö': 'öh', 'ü': 'üh', 'Eszett': 'Eszett'}
VOICE = {'en': ['-v', 'en-gb', '-s', '118', '-p', '58', '-a', '120'], 'de': ['-v', 'de', '-s', '112', '-p', '58', '-a', '120']}

def clip(lang, text):
    with tempfile.TemporaryDirectory() as t:
        w, m = os.path.join(t, 'a.wav'), os.path.join(t, 'a.mp3')
        subprocess.run(['espeak-ng'] + VOICE[lang] + ['-w', w, text], check=True, capture_output=True)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', w, '-ac', '1', '-ar', '22050', '-af', 'apad=pad_dur=0.08,volume=1.4', '-codec:a', 'libmp3lame', '-b:a', '24k', m], check=True, capture_output=True)
        return 'data:audio/mpeg;base64,' + base64.b64encode(open(m, 'rb').read()).decode()

def build(lang):
    jobs = {s: (lang, s) for s in d[lang]}
    names = EN_L if lang == 'en' else DE_L
    for ch in d['letters']:
        if ch in UML: jobs[ch] = ('de', UML[ch])
        else: jobs[ch] = (lang, names[ch.upper()])
    jobs['Eszett'] = ('de', 'Eszett')
    keys = sorted(jobs)
    with ThreadPoolExecutor(8) as ex: res = list(ex.map(lambda k: clip(jobs[k][0], jobs[k][1]), keys))
    body = json.dumps(dict(zip(keys, res)), ensure_ascii=False, separators=(',', ':'))
    voice = 'British English' if lang == 'en' else 'German'
    js = '/* Recorded fallback voice (espeak-ng, %s). Generated by tools/make_clips.py. Used only when the phone voice does not work. */\n(function(g){g.KA_CLIPS=g.KA_CLIPS||{};g.KA_CLIPS.%s=%s;})(typeof window!==\'undefined\'?window:globalThis);\n' % (voice, lang, body)
    open(os.path.join(ROOT, 'shared', 'audio-%s.js' % lang), 'w', encoding='utf-8').write(js)
    print(lang, len(keys), 'clips', round(len(js) / 1e6, 2), 'MB')
for l in ('en', 'de'): build(l)
